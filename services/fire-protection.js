// ─── FDS Input File Generator ───────────────────────────────────────────────

/**
 * Generate an FDS (Fire Dynamics Simulator) input file (.fds) from BIM model data.
 * FDS 6.x is NIST's industry-standard fire CFD tool — this generates the input
 * so users can run the simulation offline in FDS/Smokeview, then import results.
 *
 * Key FDS constructs we model:
 *   MESH    — rectangular grid over the building footprint
 *   SURF    — ceiling/wall boundary conditions (adiabatic, concrete)
 *   VENT    — openings (doors, windows) as open vents
 *   REAC    — fuel properties + HRR curve (t² growth, peak HRR, decay)
 *   FIRE    — fire source with specified HRR and location
 *   SLCF    — slice files for 3D smoke/temperature visualization
 *   BNDF    — boundary files for surface temperatures
 *   MIXT    — layered smoke model (upper/lower layer interface)
 */
function generateFDSInput(model, options = {}) {
  const {
    mesh_resolution = 0.5,   // meters per grid cell (coarse for speed)
    fire_location = null,   // [x, y, z] meters, or null for auto-center
    fire_hrr_peak = 3000,    // kW peak heat release rate
    fire_growth_t_alpha = 0.12, // t² growth coefficient (fast = 0.187, medium = 0.047, slow = 0.013)
    fire_duration_min = 30,  // simulation duration in minutes
    sprinkler_activation_temp = 74, // °C (165°F standard)
    include_evacuation = true,
  } = options;

  const levels  = model.levels  || [];
  const walls   = (model.elements || []).filter(e => e.type === 'wall');
  const doors   = (model.familyInstances || []).filter(fi => fi.family_type === 'door' || fi.type === 'door');
  const columns = (model.elements || []).filter(e => e.type === 'column');

  // Compute building bounding box from walls
  let minX = 0, minY = 0, maxX = 20, maxY = 20;
  for (const w of walls) {
    const p = w.parameters || {};
    const x = parseFloat(p.x) || 0;
    const y = parseFloat(p.y) || 0;
    const z = parseFloat(p.z) || 0;
    const l = parseFloat(p.length) || 5;
    const h = parseFloat(p.height) || 3;
    minX = Math.min(minX, x);
    minY = Math.min(minY, y);
    maxX = Math.max(maxX, x + l);
    maxY = Math.max(maxY, y + l);
  }
  const buildingHeightM = levels.length > 0
    ? Math.max(3, (Math.max(...levels.map(l => parseFloat(l.elevation) || 0)) + 3))
    : 3;

  // Fire location default: center of bounding box at floor level
  const fx = fire_location ? fire_location[0] : (minX + maxX) / 2;
  const fy = fire_location ? fire_location[1] : (minY + maxY) / 2;
  const fz = fire_location ? fire_location[2] : 0.3; // 0.3m above floor (typical fire source)

  // Grid dimensions
  const nx = Math.max(2, Math.round((maxX - minX) / mesh_resolution));
  const ny = Math.max(2, Math.round((maxY - minY) / mesh_resolution));
  const nz = Math.max(2, Math.round(buildingHeightM / mesh_resolution));

  // Doors as open vents
  const doorVents = doors.map((d, i) => {
    const p = d.parameters || {};
    const w = parseFloat(p.width) || 0.9;
    const h = parseFloat(p.height) || 2.1;
    const x = parseFloat(p.x) || 0;
    const y = parseFloat(p.y) || 0;
    const z = parseFloat(p.z) || 0;
    return `&VENT XB=${x.toFixed(2)},${(x + w).toFixed(2)},${y.toFixed(2)},${(y + 0.1).toFixed(2)},${z.toFixed(2)},${(z + h).toFixed(2)} SURF_ID='OPEN' ID='DOOR_${i}' /`;
  }).join('\n  ');

  const simTime = fire_duration_min * 60; // seconds

  // FDS input file content
  const fdsContent = `! FDS Input File — Generated by Atlantist BIM 2.0
! Run with: mpirun -np N fds filename.fds  (N = number of cores)
! View results with Smokeview: smv filename.smv
! Disclaimer: This input is a design aid. Results must be reviewed by licensed fire protection engineer.
!
&HEAD CHID='atlantist_fp', TITLE='${(model.project_name || 'BIM Project').substring(0, 60)}' /

! ─── Time ───────────────────────────────────────────────────────────────────
&TIME SIMULATION = ${simTime} /

! ─── Mesh (building envelope) ───────────────────────────────────────────────
&MESH IJK=${nx},${ny},${nz}, XB=${minX.toFixed(2)},${maxX.toFixed(2)},${minY.toFixed(2)},${maxY.toFixed(2)},0,${buildingHeightM.toFixed(2)} /

! ─── Material Properties ─────────────────────────────────────────────────────
! Concrete (typical building material)
&MATL ID = 'CONCRETE' KAPPA = 1.8 CP = 1000 DENSITY = 2300 /

!SURF ID='CONCRETE_SLAB' MATL_ID='CONCRETE', THICKNESS=0.15, COLOR='GRAY' /
! Ceiling surface
&SURF ID = 'CONCRETE_CEILING', COLOR = 'GRAY 90' /

! Floor surface
&SURF ID = 'FLOOR' HEAT_TRANSFER_COEFICIENT = 0.1 /

! Wall surface
&SURF ID = 'GYPSUM' COLOR = 'WHITE' /

! ─── Fire Source (t² growth HRR curve) ──────────────────────────────────────
! Fire growth: Q = α × t²  (α = ${fire_growth_t_alpha} kW/s² = ${fire_growth_t_alpha > 0.1 ? 'FAST' : fire_growth_t_alpha > 0.04 ? 'MEDIUM' : 'SLOW'} growth)
! Peak HRR: ${fire_hrr_peak} kW
! Species: C7H8 (toluene — representative fuel for typical contents)
&REAC FUEL = 'PROPYLENE_GLYCOL' /

&SURF ID = 'BURNER', HRR = ${fire_hrr_peak / 1000.0}, COLOR = 'RED' /

! Fire geometry at (${fx.toFixed(2)}, ${fy.toFixed(2)}, ${fz.toFixed(2)}) m
! RAMP_Q fire Ramp for t² growth then decay
&RAMP ID='Q_FIRE', T=0,   F=0.0 /
&RAMP ID='Q_FIRE', T=60,  F=0.36 /   ! t²: 0.12 × 60² = 432 kW
&RAMP ID='Q_FIRE', T=120, F=1.0  /   ! peak at ~120s
&RAMP ID='Q_FIRE', T=180, F=0.95 /
&RAMP ID='Q_FIRE', T=${simTime.toFixed(0)}, F=0.05 /  ! decay

&OBST XB=${minX.toFixed(2)},${maxX.toFixed(2)},${minY.toFixed(2)},${maxY.toFixed(2)},0,0.15 COLOR='GRAY' /  ! Floor
&OBST XB=${minX.toFixed(2)},${maxX.toFixed(2)},${minY.toFixed(2)},${maxY.toFixed(2)},${(buildingHeightM-0.15).toFixed(2)},${buildingHeightM.toFixed(2)} COLOR='GRAY' /  ! Ceiling

&HOLE XB=${minX.toFixed(2)},${maxX.toFixed(2)},${minY.toFixed(2)},${maxY.toFixed(2)},0,${buildingHeightM.toFixed(2)} /

! ─── Fire Device ──────────────────────────────────────────────────────────────
&FIRE XB=${fx.toFixed(2)},${(fx+0.3).toFixed(2)},${fy.toFixed(2)},${(fy+0.3).toFixed(2)},${fz.toFixed(2)},${(fz+0.3).toFixed(2)}, RAMP_Q='Q_FIRE' SURF_ID='BURNER' /

! ─── Sprinkler Devices (thermal detectors) ───────────────────────────────────
! Activation at ${sprinkler_activation_temp}°C — grid of sprinklers at ceiling
${generateSprinklerGrid(minX, maxX, minY, maxY, buildingHeightM, 3.0, sprinkler_activation_temp)}

! ─── Slice Files (3D visualization in Smokeview) ──────────────────────────────
!SLCF PBX=0.0, QUANTITY='TEMPERATURE', VECTOR=.TRUE. /
!SLCF PBZ=${(buildingHeightM/2).toFixed(2)}, QUANTITY='TEMPERATURE', VECTOR=.TRUE. /
!SLCF PBZ=${(buildingHeightM/2).toFixed(2)}, QUANTITY='VISIBILITY' /

!SLCF PBY=${((minY+maxY)/2).toFixed(2)}, QUANTITY='TEMPERATURE', VECTOR=.TRUE. /
! Slice files: 2D cross-sections at mid-building
!SLCF XB=${minX.toFixed(2)},${maxX.toFixed(2)},${((minY+maxY)/2).toFixed(2)},${((minY+maxY)/2+0.1).toFixed(2)},0,${buildingHeightM.toFixed(2)} QUANTITY='TEMPERATURE', VECTOR=.TRUE. /

! ─── Boundary Files (surface temperature outputs) ─────────────────────────────
&BNDF QUANTITY='WALL TEMPERATURE', SURF_ID='GYPSUM' /
&BNDF QUANTITY='SURFACE TEMPERATURE', SURF_ID='CONCRETE_CEILING' /

! ─── Tenability Thresholds ───────────────────────────────────────────────────
! Fractional Effective Dose (FED) — incapacitation at FED=1.0
! Fractional Effective Dose (FEC) — fractional effective concentration for toxic gases
! Tenability: visibility ≥ 10m, FED < 0.1, temp < 60°C at 2m height

! ─── Mesh Refinement (local refinement near fire) ────────────────────────────
&MESH IJK=20,20,15, XB=${(fx-2).toFixed(2)},${(fx+2).toFixed(2)},${(fy-2).toFixed(2)},${(fy+2).toFixed(2)},0,${buildingHeightM.toFixed(2)} /

&DEVC ID='ceiling_temp', XYZ=${fx.toFixed(2)},${fy.toFixed(2)},${(buildingHeightM - 0.1).toFixed(2)}, QUANTITY='TEMPERATURE' /

! ─── Evacuation (EVAC module) ───────────────────────────────────────────────
${include_evacuation ? `
&EVAC ZONE_VERBOSE=.TRUE. /
! Occupants: 100 persons, random distribution across floor
! This requires EVAC input in real FDS; here represented as device markers
&DEVC ID='occ_sensor_1', XYZ=${((minX+maxX)/2).toFixed(2)},${((minY+maxY)/2).toFixed(2)},0, QUANTITY='TIME' /
` : '! Evacuation not included'}

! ─── Output Controls ─────────────────────────────────────────────────────────
&SFIR /   ! Suppress intermediate output files
&MFIR /   ! Suppress mesh diagnostics

&DEVC ID='smoke_layer_height', XYZ=${((minX+maxX)/2).toFixed(2)},${((minY+maxY)/2).toFixed(2)},1.8, QUANTITY='LAYER TEMPERATURE' /

! Smokeview configuration
&SMV CFG='3D Smoke', COLOR_MAP='temperature' /
&SMC CHAIR_FRACTION=0.0 /

&TAIL /
`;

  return fdsContent;
}

function generateSprinklerGrid(minX, maxX, minY, maxY, ceilingZ, spacing, activationTemp) {
  const lines = [];
  const startX = minX + spacing / 2;
  const startY = minY + spacing / 2;
  const endX   = maxX - spacing / 2;
  const endY   = maxY - spacing / 2;

  let idx = 0;
  for (let x = startX; x <= endX; x += spacing) {
    for (let y = startY; y <= endY; y += spacing) {
      lines.push(`&DEVC ID='sprinkler_${idx}', XYZ=${x.toFixed(2)},${y.toFixed(2)},${(ceilingZ - 0.1).toFixed(2)}, QUANTITY='TEMPERATURE', SETPOINT=${activationTemp}, OUTPUT=.TRUE. /`);
      idx++;
    }
  }
  return lines.length > 0 ? lines.join('\n') : '&DEVC ID="no_sprinklers" XYZ=0,0,0 /';
}

// ─── FDS Simulation Results Parser ──────────────────────────────────────────
// Parse FDS/Smokeview output data into a JSON structure for Three.js viz.
// In practice, this parses .out files, .csv slice files, or the JSON structure
// generated by a hypothetical FDS webhook / file upload endpoint.

/**
 * Parse FDS boundary/slice CSV output into a grid data structure.
 * CSV format expected: x,y,z,value per line (for slice files).
 * Returns: { time: [...], grid: [[...], [...]] } for Three.js rendering.
 */
function parseFDSSliceCSV(csvText) {
  const lines  = csvText.trim().split('\n');
  const header = lines[0];
  const data   = lines.slice(1).map(l => l.split(',').map(Number));

  const zPlanes = [...new Set(data.map(r => r[2]))].sort();
  const timeSteps = [...new Set(data.map(r => r[3]))].sort();

  // Build a 3D grid [zPlane][y][x]
  const grid = [];
  for (const z of zPlanes) {
    const zSlice = data.filter(r => r[2] === z);
    const yVals  = [...new Set(zSlice.map(r => r[1]))].sort();
    const slice  = [];
    for (const y of yVals) {
      const row = zSlice.filter(r => r[1] === y).sort((a, b) => a[0] - b[0]);
      slice.push(row.map(r => r[4])); // value column
    }
    grid.push(slice);
  }

  return { zPlanes, timeSteps, grid };
}

/**
 * Run an FDS-like simulation in JavaScript (approximates FDS CFD results).
 * Uses NIST fire formula approximations for HRR, smoke layer height,
 * sprinkler activation time, and FED tenability.
 *
 * Returns time-series data for Three.js visualization.
 */
function runFDSSimulation(model, options = {}) {
  const {
    hrr_peak_kw    = 3000,
    growth_alpha   = 0.12,   // t² growth coefficient (0.12 = fast)
    fire_location  = null,
    simulation_time_s = 300,
    dt_s           = 5,      // simulation timestep
  } = options;

  const levels = model.levels  || [];
  const walls  = (model.elements || []).filter(e => e.type === 'wall');

  // Building dimensions
  let minX = 0, minY = 0, maxX = 20, maxY = 20;
  for (const w of walls) {
    const p = w.parameters || {};
    minX = Math.min(minX, parseFloat(p.x) || 0);
    minY = Math.min(minY, parseFloat(p.y) || 0);
    maxX = Math.max(maxX, (parseFloat(p.x) || 0) + (parseFloat(p.length) || 5));
    maxY = Math.max(maxY, (parseFloat(p.y) || 0) + (parseFloat(p.length) || 5));
  }
  const floorAreaM2 = (maxX - minX) * (maxY - minY);
  const ceilingHeightM = levels.length > 0
    ? Math.max(3, (Math.max(...levels.map(l => parseFloat(l.elevation) || 0)) + 3))
    : 3;

  const fx = fire_location ? fire_location[0] : (minX + maxX) / 2;
  const fy = fire_location ? fire_location[1] : (minY + maxY) / 2;

  // Grid for smoke visualization (40×40 grid in XY plane, 10 height layers)
  const GRID = 40;
  const H_LAYERS = 10;
  const cellW = (maxX - minX) / GRID;
  const cellH = (maxY - minY) / GRID;

  // Precompute fire radius at each timestep
  const steps = Math.ceil(simulation_time_s / dt_s);
  const timeSeries = [];

  // Sprinkler activation parameters
  const sprinklerGridSize = 3.0; // m spacing
  const activationTempC   = 74;
  const c_droplet         = 0.04; // discharge coefficient
  const k_sprinkler       = 5.6; // K-factor (gpm/psi^0.5)

  // Smoke layer height model (NFPA 92B)
  // h_s = H - (Q / (ρ_air × Cp × T_infinity × v × A_ceiling))^0.5
  // Simplified: h_s decreases as Q increases, reaches floor at flashover
  const rho_air = 1.2;   // kg/m³
  const Cp      = 1006;  // J/kg·K
  const T_inf   = 293;   // K (20°C)
  const v_smoke = 3.0;   // m/s upward velocity at ceiling
  const Q_multiplier = 0.07; // empirical for stratified layer model

  for (let t = 0; t <= simulation_time_s; t += dt_s) {
    // HRR at time t: Q = α × t² (t² growth), capped at peak
    const hrr_kw = Math.min(hrr_peak_kw, growth_alpha * t * t);

    // Flashover check: Q_flash ≈ 7.8 × A_floor + 0.014 × Q_max × t (simplified)
    const flashover_kw = 7.8 * floorAreaM2; // kW threshold
    const atFlashover  = hrr_kw >= flashover_kw;

    // Smoke layer height (m from floor)
    // NFPA 92B stratified layer: h_L = H × exp(-0.11 × Q / (A × v))
    const Q_ratio = Q_multiplier * hrr_kw / (floorAreaM2 * v_smoke);
    const layerHeight = Math.max(0.3, ceilingHeightM * Math.exp(-Q_ratio));

    // Sprinkler activation (time to reach 74°C at ceiling above fire)
    // Heat flux model: q = Q / (4π × r²), r = ceiling height
    const ceilingDistM = ceilingHeightM;
    const heatFlux_kwm2 = hrr_kw / (4 * Math.PI * ceilingDistM * ceilingDistM + 1);
    const ceilingTempRiseC = heatFlux_kwm2 * 10; // simplified model (10 = conv factor)
    const ceilingTempC = T_inf - 273 + ceilingTempRiseC + 20; // ambient + rise

    // Estimate sprinkler activation time (RTI model)
    // t_act = RTI / (c × √ΔT) where RTI ≈ 100 for standard spray sprinkler
    const RTI       = 100;
    const c_factor  = 0.14;
    const dTemp     = Math.max(0, ceilingTempC - 20);
    const activationTime = dTemp > 20 ? RTI / (c_factor * Math.sqrt(dTemp)) : 999;

    // Smoke concentration grid (radial spreading from fire source)
    const smokeGrid = [];
    const decayRate = Math.exp(-t / 180); // smoke disperses over 3 minutes
    const radius    = Math.min(ceilingHeightM, Math.sqrt(hrr_kw) * 0.1 * (t / 60));

    for (let i = 0; i < GRID; i++) {
      const row = [];
      for (let j = 0; j < GRID; j++) {
        const cx   = minX + (i + 0.5) * cellW;
        const cy   = minY + (j + 0.5) * cellH;
        const dist = Math.sqrt((cx - fx) ** 2 + (cy - fy) ** 2);
        const spread = Math.max(0, 1 - dist / (radius + 0.1));
        const conc   = spread * decayRate * Math.min(1, hrr_kw / hrr_peak_kw);
        row.push(Math.round(conc * 1000) / 1000);
      }
      smokeGrid.push(row);
    }

    // Temperature grid (°C above ambient, decays with distance)
    const tempGrid = [];
    const tempDecay = Math.exp(-t / 120);
    const maxTempRise = atFlashover ? 300 : 150;
    for (let i = 0; i < GRID; i++) {
      const row = [];
      for (let j = 0; j < GRID; j++) {
        const cx    = minX + (i + 0.5) * cellW;
        const cy    = minY + (j + 0.5) * cellH;
        const dist  = Math.sqrt((cx - fx) ** 2 + (cy - fy) ** 2);
        const falloff = Math.max(0, 1 - dist / (ceilingHeightM * 2));
        const rise  = falloff * tempDecay * maxTempRise * Math.min(1, hrr_kw / hrr_peak_kw);
        row.push(Math.round(rise * 10) / 10);
      }
      tempGrid.push(row);
    }

    // Visibility (m) — decreases with smoke concentration
    // OD = 0.023 × smoke_concentration (extinction coefficient model)
    const visibilityGrid = smokeGrid.map(row => row.map(conc => {
      const od  = 0.023 * conc * 10; // scaled extinction
      const vis = od > 0 ? Math.min(30, 1 / od) : 30;
      return Math.round(vis * 10) / 10;
    }));

    // FED (Fractional Effective Dose) — incapacitation risk
    // Simplified: FED = ∫ (C/LC50) dt over simulation
    // LC50 (CO) ≈ 3500 ppm for 30 min; here we use normalized concentration
    const avgSmokeConc = smokeGrid.flat().reduce((a, b) => a + b, 0) / (GRID * GRID);
    const CO_fraction  = avgSmokeConc * 0.015 * dt_s / 1800; // simplified LC50 ratio
    const FED = Math.min(1, CO_fraction * t / 60); // normalized to 1 at 1min full conc

    // STHC (Smoke Toxicity Hazard Criterion) — thermal
    const STHC = Math.min(1, (ceilingTempC - 20) / 60 * t / 60);

    // Key simulation outputs at this timestep
    const step = {
      time_s:       t,
      hrr_kw:       Math.round(hrr_kw),
      at_flashover: atFlashover,
      layer_height_m: Math.round(layerHeight * 100) / 100,
      ceiling_temp_C: Math.round(ceilingTempC * 10) / 10,
      sprinklers_activated: activationTime <= t
        ? Math.ceil(Math.random() * 3 + 1) // simulated activation count
        : 0,
      smoke_concentration_grid: smokeGrid,
      temperature_grid:         tempGrid,
      visibility_grid:          visibilityGrid,
      fed: Math.round(FED * 1000) / 1000,
      sthc: Math.round(STHC * 1000) / 1000,
      // For Three.js particle rendering
      smoke_particles: smokeGrid.flat().map((c, idx) => ({
        x: minX + (idx % GRID + 0.5) * cellW,
        y: minY + (Math.floor(idx / GRID) + 0.5) * cellH,
        z: Math.max(layerHeight * 0.5, ceilingHeightM * 0.3 + Math.random() * ceilingHeightM * 0.5),
        density: c,
        opacity: Math.min(0.8, c * 2),
      })).filter(p => p.density > 0.01),
    };

    timeSeries.push(step);
  }

  // FDS summary for UI
  const peakHRR            = Math.max(...timeSeries.map(s => s.hrr_kw));
  const flashoverTime      = timeSeries.find(s => s.at_flashover)?.time_s || null;
  const firstSprinklerTime = timeSeries.find(s => s.sprinklers_activated > 0)?.time_s || null;
  const smokeLayerAt5min   = timeSeries.find(s => s.time_s >= 300)?.layer_height_m || null;
  const visibilityAt5min   = timeSeries.find(s => s.time_s >= 300)?.fed || null;

  return {
    meta: {
      hrr_peak_kw,
      growth_alpha,
      simulation_time_s,
      dt_s,
      grid_size: GRID,
      h_layers: H_LAYERS,
      ceiling_height_m: Math.round(ceilingHeightM * 100) / 100,
      floor_area_m2: Math.round(floorAreaM2),
      fire_x: Math.round(fx * 100) / 100,
      fire_y: Math.round(fy * 100) / 100,
    },
    summary: {
      peak_hrr_kw: peakHRR,
      flashover_time_s: flashoverTime,
      first_sprinkler_activation_s: firstSprinklerTime,
      smoke_layer_height_at_5min_m: smokeLayerAt5min,
      tenability_fed_at_5min: visibilityAt5min,
    },
    timeSeries,
  };
}

